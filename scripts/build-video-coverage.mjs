// Generates docs/VIDEO_COVERAGE.md: Stage 2 of docs/PRD.md §15. Run: npm run videos:coverage
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { BLUEPRINT, phaseLoads } from "../lib/blueprint.ts";
import { LEARNING_MAP, parseRef } from "../lib/learning-map.ts";
import { UNIT_VIDEOS } from "../lib/unit-videos.ts";

const ROOT = path.resolve(import.meta.dirname, "..");
const read = async (p) => JSON.parse(await readFile(path.join(ROOT, p), "utf8"));
const { videos, verifiedAt } = await read("data/videos-verified.json");
const source = (await read("lib/videos-source.json")).videos;
const meta = new Map(source.map((v) => [v.key, v]));

const seconds = (spec) => { const r = parseRef(spec), v = videos[r.key]; return (r.end ?? v.durationSec) - (r.start ?? 0); };
const clock = (s) => (s >= 3600 ? `${Math.floor(s / 3600)} h ${Math.round((s % 3600) / 60)} m` : `${Math.max(1, Math.round(s / 60))} m`);
const link = (spec) => { const r = parseRef(spec), v = videos[r.key]; return `[${v.title.replace(/\|/g, "/").slice(0, 70)}](https://www.youtube.com/watch?v=${v.id}${r.start ? `&t=${r.start}s` : ""})`; };

const units = Object.entries(UNIT_VIDEOS).flatMap(([topic, subs]) => Object.entries(subs).map(([title, u]) => ({ topic, title, ...u })));
const open = units.filter((u) => u.primary === null);
const filled = units.length - open.length;

const measured = Object.fromEntries(Object.entries(LEARNING_MAP).map(([topic, entries]) => [topic, Object.fromEntries(entries.map(([title, p, , , minutes]) => [title, { watch: p.startsWith("d-") ? null : seconds(p) / 60, practise: minutes }]))]));
const actual = Object.fromEntries(units.filter((u) => u.primary).map((u) => [`${u.topic}::${u.title}`, seconds(u.primary) / 60]));
const loads = phaseLoads(measured, undefined, actual);
const total = loads.reduce((a, l) => a + l.totalHours, 0);
const titleOf = new Map(BLUEPRINT.flatMap((p) => p.modules.flatMap((m) => m.topics.map((t) => [t.id, t.title]))));

const used = new Map();
for (const u of units) if (u.primary) { const k = parseRef(u.primary).key; used.set(videos[k].channel, (used.get(videos[k].channel) ?? 0) + 1); }
const named = ["Data with Baraa", "Alex The Analyst", "Corey Schafer", "freeCodeCamp", "techTFQ", "DataTalksClub", "Databricks", "Microsoft Developer", "Guy in a Cube", "DeepLearning", "LangChain", "Dave Ebbelaar", "ArjanCodes", "Docker", "Microsoft Azure"];
const everyUse = Object.values(videos).filter((v) => v.status === "verified");
const channelCount = (n) => everyUse.filter((v) => v.channel?.toLowerCase().includes(n.toLowerCase())).length;

let md = `# URHA: video coverage\n\nStage 2 of \`docs/PRD.md\` §15. Generated by \`npm run videos:coverage\`. **The app does not show these yet.** Stage 3 moves them into the curriculum.\n\n`;
md += `Of the ${units.length} units that had no primary video, **${filled} now have one and ${open.length} are pending**. The other units already had a video primary. Every video passed the watch-page check on ${verifiedAt.slice(0, 10)}; a failed video cannot appear here.\n\n`;
md += `## What "verified" means\n\nThe watch page confirms the video exists, its title, channel, length, date and whether it embeds. Relevance is judged from its chapters or, where it has none, its title. **No video was watched**, so a lesson can still prove weak in use; those marked "title" are the first to check.\n\n`;
md += `## Study load with real video lengths\n\n| Phase | Total hours | Hours a week | Still estimated |\n|---|---|---|---|\n`;
for (const l of loads) md += `| ${l.title} | ${l.totalHours.toFixed(0)} | **${l.hoursPerWeek.toFixed(1)}** | ${(l.estimatedShare * 100).toFixed(0)}% |\n`;
md += `| **Total** | **${total.toFixed(0)}** | **${(total / (52 / 12 * 24)).toFixed(1)}** | |\n\n`;
md += `## Your named channels\n\n| Channel | Videos in the library |\n|---|---|\n${named.map((n) => `| ${n} | ${channelCount(n) || "None"} |`).join("\n")}\n`;
md += `\n## Pending units (${open.length})\n\nNothing is forced into these. The reason is what the app will show.\n\n| Topic | Unit | Reason |\n|---|---|---|\n${open.map((u) => `| ${titleOf.get(u.topic)} | ${u.title} | ${u.pending} |`).join("\n")}\n`;
md += `\n## Units with a video (${filled})\n\n| Topic | Unit | Primary | Channel | Time | Basis | Alternative |\n|---|---|---|---|---|---|---|\n`;
for (const u of units.filter((x) => x.primary)) {
  const k = parseRef(u.primary).key, v = videos[k], m = meta.get(k);
  md += `| ${titleOf.get(u.topic)} | ${u.title} | ${link(u.primary)} | ${v.channel} | ${clock(seconds(u.primary))} | ${m?.relevance ?? "reviewed earlier"} | ${u.alternative ? link(u.alternative) : "None"} |\n`;
}
await writeFile(path.join(ROOT, "docs/VIDEO_COVERAGE.md"), md);
console.log(`${filled} filled, ${open.length} pending, ${total.toFixed(0)} h`);
for (const l of loads) console.log(`${l.id} ${l.hoursPerWeek.toFixed(1)} h/week, ${(l.estimatedShare * 100).toFixed(0)}% estimated`);
