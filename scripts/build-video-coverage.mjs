// Generates docs/VIDEO_COVERAGE.md from lib/learning-map.ts. Run: npm run videos:coverage
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { PHASES } from "../lib/curriculum.ts";
import { LEARNING_MAP, parseRef } from "../lib/learning-map.ts";

const ROOT = path.resolve(import.meta.dirname, "..");
const read = async (p) => JSON.parse(await readFile(path.join(ROOT, p), "utf8"));
const { videos, verifiedAt } = await read("data/videos-verified.json");
const meta = new Map((await read("lib/videos-source.json")).videos.map((v) => [v.key, v]));
const seconds = (spec) => { const r = parseRef(spec), v = videos[r.key]; return (r.end ?? v.durationSec) - (r.start ?? 0); };
const clock = (s) => (s >= 3600 ? `${Math.floor(s / 3600)} h ${Math.round((s % 3600) / 60)} m` : `${Math.max(1, Math.round(s / 60))} m`);
const link = (spec) => { const r = parseRef(spec), v = videos[r.key]; return `[${v.title.replace(/\|/g, "/").slice(0, 70)}](https://www.youtube.com/watch?v=${v.id}${r.start ? `&t=${r.start}s` : ""})`; };

const titleOf = new Map(PHASES.flatMap((p) => p.topics.map((t) => [t.id, t.title])));
const units = Object.entries(LEARNING_MAP).flatMap(([topic, es]) => es.map(([title, primary, supplement, , , pending]) => ({ topic, title, primary, supplement, pending })));
const open = units.filter((u) => u.primary === null);
const filled = units.filter((u) => u.primary);
const verified = Object.values(videos).filter((v) => v.status === "verified");
const named = ["Data with Baraa", "Alex The Analyst", "Corey Schafer", "freeCodeCamp", "techTFQ", "DataTalksClub", "Databricks", "Microsoft Developer", "Guy in a Cube", "DeepLearning", "LangChain", "Dave Ebbelaar", "ArjanCodes", "Docker", "Microsoft Azure"];
const channel = (n) => verified.filter((v) => v.channel?.toLowerCase().includes(n.toLowerCase())).length;

let md = `# URHA: video coverage\n\nGenerated by \`npm run videos:coverage\`.\n\n**${filled.length} of ${units.length} learning units have a primary YouTube video; ${open.length} are pending.** Every video passed the watch-page check on ${verifiedAt.slice(0, 10)}; a failed video cannot appear here.\n\n`;
md += `## What "verified" means\n\nThe watch page confirms the video exists, its title, channel, length, date and whether it embeds. Relevance is judged from its chapters or, where it has none, its title. **No video was watched**, so a lesson can still prove weak in use; those marked "title" are the first to check.\n\n`;
md += `## Your named channels\n\n| Channel | Videos in the library |\n|---|---|\n${named.map((n) => `| ${n} | ${channel(n) || "None"} |`).join("\n")}\n`;
md += `\n## Pending units (${open.length})\n\n| Topic | Unit | Reason |\n|---|---|---|\n${open.map((u) => `| ${titleOf.get(u.topic)} | ${u.title} | ${u.pending} |`).join("\n")}\n`;
md += `\n## Units with a video (${filled.length})\n\n| Topic | Unit | Primary | Channel | Time | Basis | Alternative |\n|---|---|---|---|---|---|---|\n`;
for (const u of filled) {
  const k = parseRef(u.primary).key;
  const alt = u.supplement ? (u.supplement.startsWith("d-") ? "Documentation" : link(u.supplement)) : "None";
  md += `| ${titleOf.get(u.topic)} | ${u.title} | ${link(u.primary)} | ${videos[k].channel} | ${clock(seconds(u.primary))} | ${meta.get(k)?.relevance ?? "reviewed earlier"} | ${alt} |\n`;
}
await writeFile(path.join(ROOT, "docs/VIDEO_COVERAGE.md"), md);
console.log(`${filled.length} filled, ${open.length} pending`);
